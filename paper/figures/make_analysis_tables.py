"""Generate tables/robustness.tex and tables/leakage_baselines_current.tex from the analysis outputs.

Sources (runs/Anchorslot/tmi_analyses_20260929/):
  robustness_stats.json      few-object sensitivity, crop bootstrap, count/volume errors
  confusion_extended.json    confusion for flat and class-balanced flat (AnchorSlot as a check)
  uniform_filter_*.json      optional: instance score after a uniform small-component filter
and cellmap_paper_refresh_20260921/raw_diagnostics.json for the conditional baselines.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = Path("/projects/weilab/liupeng/runs/Anchorslot")
ANALYSES = RUNS / "tmi_analyses_20260929"
ROWS = [("flat", "nnU-Net"), ("cb_flat", "nnU-Net + balanced CE"), ("binary", "Binary conditional"),
        ("ternary", "Three-class conditional"), ("anchorslot", "\\method{}")]


def filtered_overall():
    out = {}
    for key, _ in ROWS:
        path = ANALYSES / f"uniform_filter_{key}_filtered.json"
        if path.exists():
            out[key] = json.loads(path.read_text())["overall"]
    return out


def robustness_table() -> None:
    stats = json.loads((ANALYSES / "robustness_stats.json").read_text())
    boot = stats["bootstrap"]["delta_overall_anchorslot_minus"]
    few = stats["without_few_object_classes"]
    quant = stats["quantification"]
    filt = filtered_overall()
    # Size-filter results are reported in the text (two variants would not fit one column).
    with_filter = False
    cols = "lccccc" + ("c" if with_filter else "")
    head = "Model & Overall & \\shortstack{Overall w/o\\\\few-object} & \\shortstack{$\\Delta$ overall\\\\(95\\% CI)}"
    head += (" & \\shortstack{Overall,\\\\size filter}" if with_filter else "")
    head += " & \\shortstack{Count\\\\error} & \\shortstack{Volume\\\\error} \\\\"
    lines = [
        "% Generated by scripts/make_analysis_tables.py from runs/Anchorslot/tmi_analyses_20260929.",
        "\\begin{table}[t]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{2.5pt}",
        "\\caption{Robustness and quantification on the 17 validation crops. Overall w/o few-object: without the "
        f"instance classes with at most 10 ground-truth objects ({', '.join(stats['few_object_classes'])}). "
        "$\\Delta$: \\method{} minus the baseline, with paired crop-bootstrap 95\\% intervals. "
        + ("Size filter: predicted components below the 1st percentile of training object volume removed for every method. " if with_filter else "")
        + "Count and volume error: median absolute relative error of predicted organelle counts "
        f"({quant['anchorslot']['count_pairs']} instance pairs) and label volumes ({quant['anchorslot']['volume_pairs']} pairs).}}",
        "\\label{tab:robustness}", f"\\begin{{tabular}}{{@{{}}{cols[0]}{cols[1:]}@{{}}}}", "\\toprule", head, "\\midrule",
    ]
    for key, name in ROWS:
        overall = stats["reproduction"][key]["overall"]
        if key == "anchorslot":
            delta = "--"
        else:
            b = boot[key]
            delta = f"{b['point']:.3f} ({b['ci95'][0]:.3f}--{b['ci95'][1]:.3f})"
        cells = [name, f"{overall:.4f}", f"{few[key]['overall']:.4f}", delta]
        if with_filter:
            cells.append(f"{filt[key]:.4f}" if key in filt else "--")
        cells += [f"{quant[key]['median_abs_rel_count_error']:.2f}", f"{quant[key]['median_abs_rel_volume_error']:.2f}"]
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (ROOT / "tables/robustness.tex").write_text("\n".join(lines) + "\n")


def leakage_table() -> None:
    ext = json.loads((ANALYSES / "confusion_extended.json").read_text())
    old = json.loads((RUNS / "cellmap_paper_refresh_20260921/raw_diagnostics.json").read_text())["models"]
    models = {"flat": ext["models"]["flat"], "cb_flat": ext["models"]["cb_flat"],
              "binary": old["binary"], "ternary": old["ternary"], "anchorslot": ext["models"]["anchorslot"]}
    for key in ("cross_group_percent", "to_background_percent"):
        if not math.isclose(ext["models"]["anchorslot"][key], old["anchorslot"][key], rel_tol=1e-12):
            raise SystemExit(f"AnchorSlot {key} differs between diagnostics runs")
    lines = [
        "% Generated by scripts/make_analysis_tables.py (confusion_extended.json + raw_diagnostics.json).",
        "\\begin{table}[t]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
        "\\caption{Raw CellMap confusion (\\%) of the 27 dynamic labels over the same annotated voxels. "
        f"Only {ext['gt_background_percent']:.3f}\\% of ground-truth voxels are background.}}",
        "\\label{tab:leakage-baselines}", "\\setlength{\\tabcolsep}{2.5pt}", "\\begin{tabular}{@{}lccccc@{}}", "\\toprule",
        "Method & \\shortstack{Cross-\\\\group} & \\shortstack{Within-\\\\group} & \\shortstack{To\\\\anchors} & \\shortstack{To back-\\\\ground} & Correct \\\\", "\\midrule",
    ]
    for key, name in ROWS:
        m = models[key]
        lines.append(f"{name} & {m['cross_group_percent']:.2f} & {m['within_group_percent']:.2f} & "
                     f"{m['to_fixed_percent']:.2f} & {m['to_background_percent']:.2f} & {m['correct_percent']:.2f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (ROOT / "tables/leakage_baselines_current.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    robustness_table()
    leakage_table()
    print("wrote tables/robustness.tex and tables/leakage_baselines_current.tex")
