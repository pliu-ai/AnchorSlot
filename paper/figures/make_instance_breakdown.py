"""Per-class instance breakdown (class-balanced flat vs AnchorSlot) for the CellMap validation crops.

Pools the official evaluator's per-crop instance counts (tp, fp, fn, hausdorff_norm_sum,
n_hausdorff) exactly as the challenge score does, checks that the pooled class scores
reproduce the reported instance scores, and writes tables/instance_breakdown.tex.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVAL = Path("/projects/weilab/liupeng/runs/Anchorslot/evaluation_matrix")
MODELS = {
    "cb": EVAL / "flat_nnunet_class_balanced/full_annotated/4nm/latest_official_metrics_extended.json",
    "as": EVAL / "anchorslot_primary/full_annotated/4nm/latest_official_metrics_extended.json",
}
REPORTED = {"cb": 0.2431, "as": 0.4939}
OUT = ROOT / "tables" / "instance_breakdown.tex"


def pool(path: Path) -> tuple[dict[str, dict[str, float]], float]:
    metrics = json.loads(path.read_text())
    classes: dict[str, dict[str, float]] = {}
    for crop, per_class in metrics.items():
        if not crop.startswith("crop"):
            continue
        for name, row in per_class.items():
            if "hausdorff_norm_sum" not in row:
                continue
            acc = classes.setdefault(name, dict(tp=0, fp=0, fn=0, hs=0.0, nh=0))
            for key, src in (("tp", "tp"), ("fp", "fp"), ("fn", "fn"), ("hs", "hausdorff_norm_sum"), ("nh", "n_hausdorff")):
                acc[key] += row[src]
    for acc in classes.values():
        f1 = 2 * acc["tp"] / max(1, 2 * acc["tp"] + acc["fp"] + acc["fn"])
        acc["score"] = math.sqrt(f1 * acc["hs"] / max(1, acc["nh"]))
    return classes, metrics["overall_instance_score"]


def main() -> None:
    pooled = {}
    for key, path in MODELS.items():
        classes, official = pool(path)
        mean = sum(c["score"] for c in classes.values()) / len(classes)
        if abs(mean - official) > 1e-9 or round(official, 4) != REPORTED[key]:
            raise SystemExit(f"{key}: pooled {mean:.6f} != official {official:.6f}")
        pooled[key] = classes

    names = sorted(pooled["as"], key=lambda n: (pooled["as"][n]["tp"] + pooled["as"][n]["fn"], n))
    gap = sum(pooled["as"][n]["score"] - pooled["cb"][n]["score"] for n in names) / len(names)
    rare = [n for n in names if pooled["as"][n]["tp"] + pooled["as"][n]["fn"] <= 10]
    rare_gap = sum(pooled["as"][n]["score"] - pooled["cb"][n]["score"] for n in rare) / len(names)

    rows = []
    for n in names:
        c, a = pooled["cb"][n], pooled["as"][n]
        objects = int(a["tp"] + a["fn"])
        rows.append(
            f"\\texttt{{{n}}} & {objects} & {int(c['tp'])} / {int(a['tp'])} & {int(c['fp'])} / {int(a['fp'])} "
            f"& {c['score']:.3f} / {a['score']:.3f} \\\\"
        )
    tot = {k: {f: int(sum(pooled[k][n][f] for n in names)) for f in ("tp", "fp")} for k in pooled}
    lines = [
        "% Generated by scripts/make_instance_breakdown.py from the official evaluator outputs:",
        *[f"%   {p}" for p in MODELS.values()],
        f"% Instance gap {gap:.4f}; classes with <=10 objects ({', '.join(rare)}) contribute {rare_gap:.4f}.",
        "\\begin{table}[t]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\caption{Instance-level breakdown on the 17 validation crops, class-balanced flat (CB) / \\method{}. "
        "Objects: ground-truth objects; TP and FP: matched and unmatched predicted objects; "
        "score: $\\sqrt{F_cH_c}$ per class.}",
        "\\label{tab:instance-breakdown}",
        "\\begin{tabular}{@{}lrccc@{}}",
        "\\toprule",
        "Class & Objects & TP & FP & Score \\\\",
        "\\midrule",
        *rows,
        "\\midrule",
        f"Total / mean & -- & {tot['cb']['tp']} / {tot['as']['tp']} & {tot['cb']['fp']} / {tot['as']['fp']} "
        f"& {REPORTED['cb']:.3f} / {REPORTED['as']:.3f} \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\par\\smallskip",
        "\\parbox{\\columnwidth}{\\scriptsize Object counts from \\method{}; one pathological pair "
        "(no pooled counts) removes one object for CB in \\texttt{cell} and for \\method{} in \\texttt{mito}.}",
        "\\end{table}",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}; gap={gap:.4f}, rare({rare})={rare_gap:.4f} ({rare_gap / gap:.1%}), totals={tot}")


if __name__ == "__main__":
    main()
