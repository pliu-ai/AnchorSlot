"""CellMap computational-cost table (tables/computational_cost.tex).

Reads the efficiency program's results (runs/Anchorslot/efficiency_20260929/results):
  efficiency_metrics.json  parameters, FLOPs per 160^3 tile, training memory (batch size 2);
  inference_timing.json    network and total time per validation volume on one L40S.
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = Path("/projects/weilab/liupeng/runs/Anchorslot/efficiency_20260929/results")
OUT = ROOT / "tables" / "computational_cost.tex"

ROWS = [  # label, metrics key, FLOPs-per-tile key, timing mode
    ("Flat nnU-Net", "flat", "flops_per_tile_uncached", "flat"),
    ("Class-balanced flat", "cb_flat", "flops_per_tile_uncached", "cb_flat"),
    (r"\method{}, per query", "anchorslot", "flops_per_tile_uncached", "anchorslot_per_group"),
    (r"\method{}, cached encoder", "anchorslot", "flops_per_tile_cached", "anchorslot_cached"),
]


def main() -> None:
    metrics = json.loads((RESULTS / "efficiency_metrics.json").read_text())["methods"]
    timing = json.loads((RESULTS / "inference_timing.json").read_text())
    checks = timing["checks"]["cached_vs_per_group_label_diff_voxels"]
    if len(checks) != 17 or any(checks.values()):
        raise SystemExit(f"cached and per-query label maps differ: {checks}")

    lines = []
    for label, key, flops_key, mode in ROWS:
        m = metrics[key]
        train_bs2 = next(t for t in m["training"] if t["batch_size"] == 2)
        times = timing["modes"][mode]["timings"].values()
        network = statistics.mean(t["network_s"] for t in times)
        total = statistics.mean(t["total_s"] for t in times)
        lines.append(
            f"{label} & {m['inference']['params'] / 1e6:.2f} & "
            f"{m['inference'][flops_key] / 1e12:.1f} & {train_bs2['peak_allocated_bytes'] / 1e9:.1f} & "
            f"{network:.1f} & {total:.1f} \\\\")

    table = "\n".join([
        "% Generated by scripts/make_cost_table.py from runs/Anchorslot/efficiency_20260929/results.",
        r"\begin{table}[t]",
        r"\centering",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{2.5pt}",
        r"\caption{CellMap cost on one NVIDIA L40S GPU. TFLOPs per $160^3$ tile with eight mirrors (and 13 queries "
        r"for \method{}); peak training memory at batch size 2; mean network and total time per validation volume.}",
        r"\label{tab:cost}",
        r"\begin{tabular}{@{}lccccc@{}}",
        r"\toprule",
        r"Method & Params (M) & TFLOPs & Mem.\ (GB) & Net.\ (s) & Total (s) \\",
        r"\midrule",
        *lines,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ])
    OUT.write_text(table)
    print(table)


if __name__ == "__main__":
    main()
